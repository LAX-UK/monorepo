/**
 * Regenerates packages/datetime/src/windows-zones.generated.ts from the Unicode CLDR file
 * `windowsZones.xml` (common/supplemental/windowsZones.xml in https://github.com/unicode-org/cldr).
 *
 *   node scripts/generate-windows-zones.mjs path/to/windowsZones.xml
 *
 * Each IANA zone maps to the Windows zone ID that CLDR gives for it; where CLDR lists a zone under
 * several territories the global (001) entry wins.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/generate-windows-zones.mjs path/to/windowsZones.xml");
  process.exit(1);
}

const xml = readFileSync(source, "utf8");
const version = /<mapTimezones otherVersion="([^"]+)" typeVersion="([^"]+)"/.exec(xml);
const entries = new Map();
const global = new Set();
for (const match of xml.matchAll(
  /<mapZone other="([^"]+)" territory="([^"]+)" type="([^"]+)"\/>/g,
)) {
  const [, windows, territory, types] = match;
  for (const iana of types.split(" ")) {
    if (global.has(iana)) continue;
    entries.set(iana, windows);
    if (territory === "001") global.add(iana);
  }
}

// CLDR keeps the retired spellings; the zone list offers the current ones, which name the same zone.
const CURRENT_SPELLING = {
  "Asia/Kolkata": "Asia/Calcutta",
  "Asia/Kathmandu": "Asia/Katmandu",
  "Asia/Yangon": "Asia/Rangoon",
  "Asia/Ho_Chi_Minh": "Asia/Saigon",
  "Europe/Kyiv": "Europe/Kiev",
  "America/Nuuk": "America/Godthab",
  "Atlantic/Faroe": "Atlantic/Faeroe",
  "Pacific/Kanton": "Pacific/Enderbury",
};
for (const [current, retired] of Object.entries(CURRENT_SPELLING)) {
  if (!entries.has(current) && entries.has(retired)) entries.set(current, entries.get(retired));
}

const rows = [...entries.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([iana, windows]) => `  ${JSON.stringify(iana)}: ${JSON.stringify(windows)},`)
  .join("\n");

const out = `// Generated by scripts/generate-windows-zones.mjs. Do not edit by hand.
// Source: Unicode CLDR common/supplemental/windowsZones.xml (otherVersion ${version?.[1] ?? "unknown"}, typeVersion ${version?.[2] ?? "unknown"}).
// IANA zone name to Windows zone ID, as ATG's GAP API names zones.
export const WINDOWS_ZONE_BY_IANA: Readonly<Record<string, string>> = {
${rows}
};
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "../packages/datetime/src/windows-zones.generated.ts",
);
writeFileSync(target, out);
console.log(`${entries.size} zones written to ${target}`);
