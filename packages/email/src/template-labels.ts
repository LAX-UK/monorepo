export type EmailTemplateDescription = { label: string; essential: boolean };

/** Plain-words label for a stored template id; unknown ids (retired templates) read generically. */
export function describeEmailTemplate(template: string): EmailTemplateDescription {
  const label = (EMAIL_TEMPLATE_LABELS as Record<string, string | undefined>)[template];
  return { label: label ?? "Email", essential: !isOptionalEmailTemplate(template) };
}
