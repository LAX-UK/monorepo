"""Regenerates src/lockup/descriptor-glyphs.ts: Montserrat capitals converted to SVG outlines.

Lockups ship as pure vector files so they render identically wherever fonts are not loaded
(emails, hosted sign-in, OG images). Run this only when the descriptor weight changes:

    python3 -m venv /tmp/lax-glyphs && /tmp/lax-glyphs/bin/pip install fonttools brotli
    /tmp/lax-glyphs/bin/python packages/branding/scripts/outline-descriptor-glyphs.py
    pnpm exec biome check --write packages/branding/src/lockup/descriptor-glyphs.ts
    pnpm --filter @auction/branding generate:lockups

The source is the Montserrat variable font already shipped in packages/branding/fonts, pinned to
DESCRIPTOR_WEIGHT. That weight is the one at which the stem of "I" matches the stem of the "I" in
the outlined BID of the Bid lockup (11.24 units at a 46.14 unit cap height).
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

PACKAGE = Path(__file__).resolve().parent.parent
FONT = PACKAGE / "fonts" / "montserrat-latin-wght-normal.woff2"
OUTPUT = PACKAGE / "src" / "lockup" / "descriptor-glyphs.ts"
DESCRIPTOR_WEIGHT = 720
LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def main() -> None:
    font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": DESCRIPTOR_WEIGHT})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap_height = font["OS/2"].sCapHeight

    rows = []
    for letter in LETTERS:
        glyph = glyphs[cmap[ord(letter)]]
        bounds = BoundsPen(glyphs)
        glyph.draw(bounds)
        # Flip y so the baseline is 0 and capitals rise into negative y, like the SVG canvas.
        path = SVGPathPen(glyphs, ntos=lambda v: f"{round(v, 1):g}")
        glyph.draw(TransformPen(path, (1, 0, 0, -1, 0, 0)))
        rows.append(
            f"  {letter}: {{ advance: {glyph.width}, xMin: {round(bounds.bounds[0], 1):g}, "
            f'xMax: {round(bounds.bounds[2], 1):g}, d: "{path.getCommands()}" }},'
        )

    OUTPUT.write_text(
        "/**\n"
        " * Montserrat capitals as SVG outlines (font units, baseline at y = 0, capitals rise into\n"
        f" * negative y). Generated by scripts/outline-descriptor-glyphs.py at weight {DESCRIPTOR_WEIGHT};\n"
        " * do not edit by hand.\n"
        " */\n"
        "export type DescriptorGlyph = { advance: number; xMin: number; xMax: number; d: string };\n\n"
        f"export const DESCRIPTOR_FONT_CAP_HEIGHT = {cap_height};\n\n"
        "export const DESCRIPTOR_GLYPHS: Readonly<Record<string, DescriptorGlyph>> = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )


if __name__ == "__main__":
    main()
