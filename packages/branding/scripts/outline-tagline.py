"""Regenerates src/lockup/tagline-paths.ts: the "London / Art Exchange(R) / Marylebone" tagline of
the LAX London Art Exchange lockup, converted to SVG outlines so no font is needed at runtime.

    python3 -m venv /tmp/lax-glyphs && /tmp/lax-glyphs/bin/pip install fonttools brotli
    /tmp/lax-glyphs/bin/python packages/branding/scripts/outline-tagline.py
    pnpm exec biome check --write packages/branding/src/lockup/tagline-paths.ts
    pnpm --filter @auction/branding generate:lockups

The wordmark artwork this lockup replaces was a 500 x 114 px raster set in a geometric sans we do
not ship. Montserrat (the shared LAX face) is the closest family we have, so each line is set at
the weight, size and width that overlaps that raster best, and every letter is placed at the
position measured against it (Montserrat's own spacing is wider). Positions are in raster pixels;
PX_SCALE, PX_X and PX_Y map them into the lockup's coordinate space, which is the space of the
plain LAX mark (see lax-mark-paths.ts): they were fitted by overlaying the mark on the raster.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

PACKAGE = Path(__file__).resolve().parent.parent
FONT = PACKAGE / "fonts" / "montserrat-latin-wght-normal.woff2"
OUTPUT = PACKAGE / "src" / "lockup" / "tagline-paths.ts"

# Raster pixel -> lockup unit: unit = (pixel - offset) / PX_SCALE.
PX_SCALE = 0.386
PX_X = -1.0
PX_Y = -0.25

# name, weight, size in raster px per em, horizontal squeeze, baseline y, glyph -> pen x.
LINES = [
    (
        "london",
        560,
        39.5,
        0.92,
        28.25,
        [("L", 243.5), ("o", 260.98), ("n", 283.77), ("d", 308.38), ("o", 333.15), ("n", 356.31)],
    ),
    (
        "artExchange",
        580,
        39,
        0.9,
        74,
        [
            ("A", 244.25),
            ("r", 269.65),
            ("t", 283.85),
            ("E", 305.53),
            ("x", 325.69),
            ("c", 343.89),
            ("h", 366.0),
            ("a", 393.04),
            ("n", 415.03),
            ("g", 440.36),
            ("e", 464.47),
        ],
    ),
    (
        "marylebone",
        420,
        26,
        0.94,
        107.75,
        [
            ("M", 241.5),
            ("a", 265.09),
            ("r", 278.53),
            ("y", 287.74),
            ("l", 300.31),
            ("e", 305.93),
            ("b", 320.49),
            ("o", 337.34),
            ("n", 351.96),
            ("e", 367.75),
        ],
    ),
]

# The (R) belongs to the "Art Exchange" line but is a superscript: own size and origin (px).
REGISTERED = ("artExchange", "registered", 580, 39 * 0.475, 1.0, 486.25, 56.75)

_instances: dict[int, tuple] = {}


def instance(weight: int):
    if weight not in _instances:
        font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": weight})
        _instances[weight] = (font.getGlyphSet(), font.getBestCmap(), font["head"].unitsPerEm)
    return _instances[weight]


def outline(weight, glyph_name, size, squeeze, pen_x, baseline, sink, bounds):
    glyphs, _, upm = instance(weight)
    kx = size * squeeze / (upm * PX_SCALE)
    ky = size / (upm * PX_SCALE)
    matrix = (kx, 0, 0, -ky, (pen_x - PX_X) / PX_SCALE, (baseline - PX_Y) / PX_SCALE)
    glyphs[glyph_name].draw(TransformPen(sink, matrix))
    glyphs[glyph_name].draw(TransformPen(bounds, matrix))


def main() -> None:
    rows = []
    bounds = BoundsPen(None)
    for name, weight, size, squeeze, baseline, placed in LINES:
        glyphs, cmap, _ = instance(weight)
        sink = SVGPathPen(None, ntos=lambda v: f"{round(v, 1):g}")
        for letter, pen_x in placed:
            outline(weight, cmap[ord(letter)], size, squeeze, pen_x, baseline, sink, bounds)
        if name == REGISTERED[0]:
            _, glyph, r_weight, r_size, r_squeeze, r_x, r_baseline = REGISTERED
            r_glyphs, r_cmap, _ = instance(r_weight)
            outline(r_weight, r_cmap[ord("®")], r_size, r_squeeze, r_x, r_baseline, sink, bounds)
        rows.append((name, sink.getCommands()))

    x0, y0, x1, y1 = bounds.bounds
    OUTPUT.write_text(
        "/**\n"
        " * The tagline of the LAX London Art Exchange lockup as SVG outlines, in the coordinate space of\n"
        " * the plain LAX mark. Generated by scripts/outline-tagline.py; do not edit by hand.\n"
        " */\n"
        f"export const TAGLINE_BOUNDS = {{ x: {x0:.1f}, y: {y0:.1f}, right: {x1:.1f}, bottom: {y1:.1f} }} as const;\n\n"
        "export const TAGLINE_PATHS: readonly string[] = [\n"
        + "".join(f'  "{d}",\n' for _, d in rows)
        + "];\n"
    )


if __name__ == "__main__":
    main()
