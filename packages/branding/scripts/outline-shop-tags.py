"""Regenerates src/lockup/shop-tag-paths.ts: three candidate ways to add "Shop" to the London Art
Exchange wordmark, as SVG outlines in the wordmark's coordinate space. Design checkpoint only.

    python3 -m venv /tmp/lax-glyphs && /tmp/lax-glyphs/bin/pip install fonttools brotli
    /tmp/lax-glyphs/bin/python packages/branding/scripts/outline-shop-tags.py
    pnpm exec biome check --write packages/branding/src/lockup/shop-tag-paths.ts

Positions are in the raster pixels outline-tagline.py uses, so each tag sits on the same grid as
"London / Art Exchange(R) / Marylebone":

- tagLine: ".SHOP" after "Marylebone", on its baseline, in capitals the height of its capitals,
  like Bid's ".BID" tag.
- besideName: "Shop" after "Art Exchange(R)", in the weight and size of that line.
- underMark: a small, tracked "SHOP" under the LAX mark, left-aligned with it.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

PACKAGE = Path(__file__).resolve().parent.parent
FONT = PACKAGE / "fonts" / "montserrat-latin-wght-normal.woff2"
OUTPUT = PACKAGE / "src" / "lockup" / "shop-tag-paths.ts"

# Same raster -> lockup mapping as outline-tagline.py.
PX_SCALE = 0.386
PX_X = -1.0
PX_Y = -0.25

# name, text, weight, size (px per em), squeeze, start x (px), baseline (px), extra tracking (px).
TAGS = [
    ("tagLine", ".SHOP", 640, 23.5, 0.94, 386.5, 107.75, 1.6),
    ("besideName", "Shop", 580, 39, 0.9, 506.0, 74, -0.6),
    ("underMark", "SHOP", 620, 23.5, 1.0, 1.0, 136.0, 7.0),
]

_instances: dict[int, tuple] = {}


def instance(weight: int):
    if weight not in _instances:
        font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": weight})
        _instances[weight] = (
            font.getGlyphSet(),
            font.getBestCmap(),
            font["head"].unitsPerEm,
            font["hmtx"],
        )
    return _instances[weight]


def main() -> None:
    rows = []
    for name, text, weight, size, squeeze, start, baseline, tracking in TAGS:
        glyphs, cmap, upm, hmtx = instance(weight)
        sink = SVGPathPen(None, ntos=lambda v: f"{round(v, 1):g}")
        bounds = BoundsPen(None)
        pen_x = start
        for letter in text:
            glyph_name = cmap[ord(letter)]
            kx = size * squeeze / (upm * PX_SCALE)
            ky = size / (upm * PX_SCALE)
            matrix = (kx, 0, 0, -ky, (pen_x - PX_X) / PX_SCALE, (baseline - PX_Y) / PX_SCALE)
            glyphs[glyph_name].draw(TransformPen(sink, matrix))
            glyphs[glyph_name].draw(TransformPen(bounds, matrix))
            advance, _ = hmtx[glyph_name]
            pen_x += advance * size * squeeze / upm + tracking
        x0, y0, x1, y1 = bounds.bounds
        rows.append((name, sink.getCommands(), (x0, y0, x1, y1)))

    body = "".join(
        f'  {name}: {{\n    d: "{d}",\n'
        f"    bounds: {{ x: {b[0]:.1f}, y: {b[1]:.1f}, right: {b[2]:.1f}, bottom: {b[3]:.1f} }},\n  }},\n"
        for name, d, b in rows
    )
    OUTPUT.write_text(
        "/**\n"
        ' * Candidate "Shop" tags for the London Art Exchange wordmark, as SVG outlines in the\n'
        " * wordmark's coordinate space. Generated by scripts/outline-shop-tags.py; do not edit by hand.\n"
        " */\n"
        "export const SHOP_TAG_PATHS = {\n" + body + "} as const;\n"
    )


if __name__ == "__main__":
    main()
