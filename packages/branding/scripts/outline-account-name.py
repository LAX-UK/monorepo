"""Regenerates src/lockup/account-name-paths.ts: the "Account / Centre(R)" name of the LAX Account
lockup, converted to SVG outlines so no font is needed at runtime.

    python3 -m venv /tmp/lax-glyphs && /tmp/lax-glyphs/bin/pip install fonttools brotli
    /tmp/lax-glyphs/bin/python packages/branding/scripts/outline-account-name.py
    pnpm exec biome check --write packages/branding/src/lockup/account-name-paths.ts
    pnpm --filter @auction/branding generate:lockups

The name is built to the measurements of the "Auction / Xchange(R)" name in the Bid lockup master
so the two lockups read as one family: the same cap height (70.39 units), the same two baselines
(77.88 and 199.25), the same left edge relative to the mark, the same gap before the (R) and the
same (R) size and height. Bid's own face is not available as a font, so the words are set in
Montserrat (the shared LAX face) at semibold, squeezed a little horizontally because Bid's letters
are narrower than Montserrat's. Coordinates are in the space of the plain LAX mark, whose X sits
18 units left of Bid's, so every Bid x position is moved by that amount.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

PACKAGE = Path(__file__).resolve().parent.parent
FONT = PACKAGE / "fonts" / "montserrat-latin-wght-normal.woff2"
OUTPUT = PACKAGE / "src" / "lockup" / "account-name-paths.ts"

WEIGHT = 600
# Measured on the Bid master: the cap height of "A" and "X", and the two baselines.
CAP_HEIGHT = 70.39
BASELINES = {"account": 77.88, "centre": 199.25}
# Pen origin of both lines: Bid's "A" ink starts at 623.23, minus the plain mark's 18 unit shift,
# plus the "A" side bearing (negative, so the pen sits just right of the ink).
PEN_X = 605.74
# Bid's letters are narrower than Montserrat's: Auction is 0.92 and Xchange 0.96 of its width.
SQUEEZE = 0.94
# The (R) on Bid's second line: its ink box and the gap from the last letter of the line.
REGISTERED_SIZE = (34.23, 34.77)
REGISTERED_GAP = 11.8
REGISTERED_TOP = 118.43


def main() -> None:
    font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": WEIGHT})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    cap = font["OS/2"].sCapHeight
    ky = CAP_HEIGHT / cap
    kx = ky * SQUEEZE

    bounds = BoundsPen(None)
    rows = []
    line_right = {}
    for name, word in (("account", "Account"), ("centre", "Centre")):
        sink = SVGPathPen(None, ntos=lambda v: f"{round(v, 1):g}")
        pen = PEN_X
        right = 0.0
        for letter in word:
            glyph = glyphs[cmap[ord(letter)]]
            matrix = (kx, 0, 0, -ky, pen, BASELINES[name])
            glyph.draw(TransformPen(sink, matrix))
            glyph.draw(TransformPen(bounds, matrix))
            box = BoundsPen(glyphs)
            glyph.draw(box)
            if box.bounds:
                right = pen + box.bounds[2] * kx
            pen += glyph.width * kx
        line_right[name] = right
        if name == "centre":
            glyph = glyphs[cmap[ord("®")]]
            box = BoundsPen(glyphs)
            glyph.draw(box)
            x0, y0, x1, y1 = box.bounds
            scale = REGISTERED_SIZE[1] / (y1 - y0)
            origin_x = right + REGISTERED_GAP - x0 * scale
            origin_y = REGISTERED_TOP + y1 * scale
            matrix = (scale, 0, 0, -scale, origin_x, origin_y)
            glyph.draw(TransformPen(sink, matrix))
            glyph.draw(TransformPen(bounds, matrix))
        rows.append(sink.getCommands())

    x0, y0, x1, y1 = bounds.bounds
    OUTPUT.write_text(
        "/**\n"
        " * The name of the LAX Account lockup, \"Account / Centre\" and the registered mark, as SVG\n"
        " * outlines in the coordinate space of the plain LAX mark. Generated by\n"
        " * scripts/outline-account-name.py; do not edit by hand.\n"
        " */\n"
        f"export const ACCOUNT_NAME_BOUNDS = {{ x: {x0:.1f}, y: {y0:.1f}, right: {x1:.1f}, bottom: {y1:.1f} }} as const;\n\n"
        "export const ACCOUNT_NAME_PATHS: readonly string[] = [\n"
        + "".join(f'  "{d}",\n' for d in rows)
        + "];\n"
    )
    print(line_right, x0, y0, x1, y1)


if __name__ == "__main__":
    main()
